/**
 * Generate src/data/serviceIndex.js - the slim, eagerly-loaded view of the
 * service catalogue.
 *
 *   npm run services:index
 *
 * WHY
 * ---
 * src/data/services.js is 41 KB of prose. It was imported by Navbar, Footer,
 * Services, Gallery, ServiceDetail and the whole SEO layer, so every visitor
 * downloaded all 13 services' full descriptions, standards lists, "why choose
 * us" copy and CTAs - on every page, including the homepage - to render a
 * dropdown of links that needs four fields.
 *
 * Measured with `npm run measure:services`, which is why the split is
 * justified: 10.9 KiB gzipped, 85.9% of the module, was being sent to render
 * navigation.
 *
 * WHAT IS IN THE INDEX
 * --------------------
 *   id, title, category  - Navbar and Footer (links and grouping)
 *   text                 - routeMeta.js, which builds each service page's meta
 *                         description from it
 *
 * `text` is the non-obvious one. It is tempting to leave it in the full module
 * on the grounds that only detail pages need descriptions, but routeMeta.js is
 * imported by Seo.jsx and therefore ships on every page. Keeping `text` in the
 * full module would pull all 13 descriptions straight back into the critical
 * path through the back door, and the whole exercise would achieve nothing.
 *
 * WHY IT IS GENERATED
 * -------------------
 * Hand-maintaining a second copy of the catalogue is a synchronisation hazard:
 * add a service to services.js, forget the index, and the navbar silently
 * omits it with no error anywhere. Generating the index from the real module
 * means the two cannot disagree about which services exist. `npm run verify`
 * runs this with --check and fails if the committed file is stale, so a
 * forgotten regeneration is caught at build time rather than in production.
 *
 * The output is committed, so the build itself needs no generation step.
 */
import fs from 'node:fs'
import path from 'node:path'
import zlib from 'node:zlib'
import { pathToFileURL } from 'node:url'

const ROOT = process.cwd()
const SOURCE = path.join(ROOT, 'src', 'data', 'services.js')
const OUTPUT = path.join(ROOT, 'src', 'data', 'serviceIndex.js')
const CHECK_ONLY = process.argv.includes('--check')

// The only fields the eagerly-loaded index carries. Anything not listed here
// stays in services.js and loads only where it is displayed.
const INDEX_FIELDS = ['id', 'title', 'category', 'text']

// --- read the catalogue -----------------------------------------------------
// Import the real module rather than parsing its text, so this cannot disagree
// with the runtime about what the data is.
const { serviceSections, disciplines, disciplineLabels } = await import(
  pathToFileURL(SOURCE).href
)

const index = serviceSections.map((service) =>
  Object.fromEntries(INDEX_FIELDS.map((field) => [field, service[field]]))
)

// The `standards` strings, in their own tiny module.
//
// jsonld.js needs this field to emit the OfferCatalog's NFPA citations, filtered
// through verifiedStandards() so only the four standards confirmed in
// PRODUCT.md are ever published. It is prose, so it lives in the full catalogue
// - but jsonld.js is reachable from Seo.jsx via routeMeta.js, so importing the
// 36 KB catalogue for one short string per service would undo the entire split.
// Hence the separate module.
const standards = Object.fromEntries(
  serviceSections.map((s) => [s.id, s.standards]).filter(([, v]) => v !== undefined)
)

// --- fail loudly rather than emit a broken index ---------------------------
const problems = []
for (const [i, service] of serviceSections.entries()) {
  for (const field of INDEX_FIELDS) {
    if (service[field] === undefined || service[field] === null) {
      problems.push(`services.js entry ${i} (${service.id}) has no "${field}"`)
    }
  }
}
if (index.length !== serviceSections.length) {
  problems.push('index length does not match the catalogue')
}
if (problems.length) {
  console.error('\n  cannot generate the service index:')
  for (const p of problems) console.error(`    - ${p}`)
  console.error('')
  process.exit(1)
}

// --- emit ------------------------------------------------------------------
const banner = `/**
 * Slim index of the service catalogue. GENERATED by
 * scripts/generate-service-index.mjs - do not edit by hand. Run
 * \`npm run services:index\` after changing src/data/services.js.
 *
 * Carries only ${INDEX_FIELDS.join(', ')}:
 *   id, title, category  Navbar and Footer render links and grouping from these
 *   text                 routeMeta.js builds each service page's meta description
 *
 * The remaining ~36 KB of prose lives in services.js and is loaded only by the
 * pages that actually display it.
 *
 * The discipline taxonomy is re-exported unchanged: it is four short objects,
 * Navbar groups the dropdown by it, and duplicating it here would be a second
 * source of truth for no saving.
 */
`

const standardsBanner = `/**
 * Standards strings, keyed by service id.
 *
 * GENERATED by scripts/generate-service-index.mjs - do not edit by hand. Run
 * \`npm run services:index\` after changing src/data/services.js.
 *
 * WHY THIS EXISTS SEPARATELY
 * --------------------------
 * src/seo/jsonld.js builds an OfferCatalog citing the standards each service
 * works to, filtered through verifiedStandards() so only the four NFPA numbers
 * confirmed in PRODUCT.md are ever emitted. That needs the \`standards\` field,
 * which is prose and lives in the 36 KB catalogue.
 *
 * jsonld.js is reachable from Seo.jsx via routeMeta.js, so importing the full
 * catalogue for one short string per service would put that prose back into
 * the critical path of every page and undo the split entirely.
 */
`

const taxonomy = `export const disciplines = ${JSON.stringify(disciplines, null, 2)}

export const disciplineLabels = ${JSON.stringify(disciplineLabels, null, 2)}
`

const body = `${banner}
export const serviceIndex = ${JSON.stringify(index, null, 2)}

export const serviceIndexById = Object.fromEntries(
  serviceIndex.map((s) => [s.id, s])
)

${taxonomy}`

const standardsBody = `${standardsBanner}
export const serviceStandards = ${JSON.stringify(standards, null, 2)}

/** The \`standards\` string for a service, or undefined if it declares none. */
export function standardsFor(serviceId) {
  return serviceStandards[serviceId]
}
`

const STANDARDS_OUTPUT = path.join(ROOT, 'src', 'data', 'serviceStandards.js')
const artefacts = [
  { file: OUTPUT, body, label: 'serviceIndex.js' },
  { file: STANDARDS_OUTPUT, body: standardsBody, label: 'serviceStandards.js' },
]

// --- write, or verify the committed copies are current ----------------------
if (CHECK_ONLY) {
  const stale = []
  for (const { file, body: expected, label } of artefacts) {
    const existing = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : ''
    if (existing !== expected) stale.push(label)
  }
  if (stale.length) {
    console.error(
      `\n  stale or missing: ${stale.join(', ')}.` +
        '\n  Run `npm run services:index` and commit the result.\n'
    )
    process.exit(1)
  }
  console.log(
    `  serviceIndex.js is current (${serviceSections.length} services, ` +
      `${INDEX_FIELDS.length} fields each)`
  )
  console.log(`  serviceStandards.js is current (${Object.keys(standards).length} entries)`)
} else {
  for (const { file, body: content, label } of artefacts) {
    fs.writeFileSync(file, content, 'utf8')
    const gz = zlib.gzipSync(Buffer.from(content, 'utf8'), { level: 9 }).length
    console.log(
      `\n  wrote src/data/${label} - ${(content.length / 1024).toFixed(1)} KiB raw / ` +
        `${(gz / 1024).toFixed(1)} KiB gzipped`
    )
  }
  console.log(`  index fields kept : ${INDEX_FIELDS.join(', ')}`)
  console.log(`  standards strings : ${Object.keys(standards).length}`)
  console.log('  prose now loads only where it is displayed\n')
}
